CREATE SCHEMA IF NOT EXISTS admin;

CREATE TABLE admin.migration_ownership (
    owner_name varchar(100) PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT migration_ownership_admin_service CHECK (owner_name = 'admin-service')
);
INSERT INTO admin.migration_ownership(owner_name) VALUES ('admin-service');

CREATE TABLE admin.admin_account (
    id uuid PRIMARY KEY,
    login_id varchar(100) NOT NULL UNIQUE,
    display_name varchar(100) NOT NULL,
    password_hash varchar(100) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    failed_login_count integer NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    locked_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE admin.admin_role (code varchar(50) PRIMARY KEY);
CREATE TABLE admin.admin_permission (code varchar(100) PRIMARY KEY);
CREATE TABLE admin.admin_account_role (
    account_id uuid REFERENCES admin.admin_account(id) ON DELETE CASCADE,
    role_code varchar(50) REFERENCES admin.admin_role(code),
    PRIMARY KEY (account_id, role_code)
);
CREATE TABLE admin.admin_role_permission (
    role_code varchar(50) REFERENCES admin.admin_role(code) ON DELETE CASCADE,
    permission_code varchar(100) REFERENCES admin.admin_permission(code),
    PRIMARY KEY (role_code, permission_code)
);
CREATE TABLE admin.admin_security_audit_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id uuid,
    target_account_id uuid,
    event_type varchar(100) NOT NULL,
    request_id varchar(100),
    success boolean NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

