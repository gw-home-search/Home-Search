CREATE TABLE news.ai_research_seed_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start date NOT NULL,
    period_end date NOT NULL,
    bucket_list jsonb NOT NULL,
    target_candidates_per_bucket integer NOT NULL,
    model varchar(128) NOT NULL,
    prompt_version varchar(64) NOT NULL,
    schema_version varchar(64) NOT NULL,
    output_manifest_hash char(64) NOT NULL,
    candidate_count integer NOT NULL DEFAULT 0,
    approved_count integer NOT NULL DEFAULT 0,
    rejected_count integer NOT NULL DEFAULT 0,
    status varchar(16) NOT NULL,
    failure_reason text,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_research_seed_run_period_valid CHECK (period_start <= period_end),
    CONSTRAINT ai_research_seed_run_bucket_list_array CHECK (jsonb_typeof(bucket_list) = 'array'),
    CONSTRAINT ai_research_seed_run_target_positive CHECK (target_candidates_per_bucket > 0),
    CONSTRAINT ai_research_seed_run_output_manifest_hash_sha256 CHECK (output_manifest_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ai_research_seed_run_status_allowed CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ai_research_seed_run_non_negative_counts CHECK (
        candidate_count >= 0
        AND approved_count >= 0
        AND rejected_count >= 0
    )
);

CREATE INDEX ai_research_seed_run_started_at_idx ON news.ai_research_seed_run (started_at DESC);
CREATE INDEX ai_research_seed_run_status_started_at_idx ON news.ai_research_seed_run (status, started_at DESC);

