DROP VIEW news.signal_dataset_view;

CREATE VIEW news.signal_dataset_view AS
SELECT
    observation.source,
    observation.source_key,
    observation.discovery_method,
    observation.availability_basis,
    observation.verification_status,
    observation.model_dataset_tier,
    observation.review_note_path,
    observation.publisher,
    observation.title,
    observation.url,
    observation.published_at,
    observation.provider_pub_at,
    observation.first_seen_at,
    feature.feature_date_kst,
    observation.news_date_kst,
    feature.region_tags,
    feature.complex_candidates,
    feature.topic_tags,
    feature.impact_target,
    feature.impact_direction,
    feature.sentiment,
    feature.confidence,
    feature.extraction_version,
    feature.evidence_level
FROM news.signal_feature feature
JOIN news.article_observation observation
    ON observation.id = feature.article_observation_id;

CREATE VIEW news.model_experiment_signal_view AS
SELECT *
FROM news.signal_dataset_view
WHERE model_dataset_tier IN ('EXPERIMENTAL_SEED', 'OBSERVED_SIGNAL');

CREATE VIEW news.production_observed_signal_view AS
SELECT *
FROM news.signal_dataset_view
WHERE model_dataset_tier = 'OBSERVED_SIGNAL';
