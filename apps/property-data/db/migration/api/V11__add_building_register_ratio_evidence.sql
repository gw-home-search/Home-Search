CREATE TABLE public.building_register_collection_campaign (
    collection_id uuid PRIMARY KEY,
    mode character varying(16) NOT NULL,
    strategy character varying(24) NOT NULL,
    from_complex_id bigint,
    to_complex_id bigint NOT NULL,
    status character varying(24) NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    completed_at timestamp with time zone,
    CONSTRAINT ck_brc_campaign_mode CHECK (mode IN ('missing', 'retry')),
    CONSTRAINT ck_brc_campaign_strategy CHECK (strategy IN ('ADAPTIVE', 'FULL_HIERARCHY')),
    CONSTRAINT ck_brc_campaign_status CHECK (status IN ('CREATED', 'COLLECTING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_brc_campaign_range CHECK (
        to_complex_id > 0
        AND (from_complex_id IS NULL OR (from_complex_id > 0 AND from_complex_id <= to_complex_id))
    ),
    CONSTRAINT ck_brc_campaign_completion CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND completed_at IS NULL)
    )
);

CREATE TABLE public.building_register_collection_target (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id uuid NOT NULL REFERENCES public.building_register_collection_campaign(collection_id),
    target_ordinal bigint NOT NULL,
    complex_id bigint NOT NULL REFERENCES public.complex(id),
    pnu character varying(19) NOT NULL,
    initial_bc_rat numeric(6,2),
    initial_vl_rat numeric(6,2),
    initial_bld_mgm_bld_rgst_pk character varying(255),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT uq_brc_target_collection_complex UNIQUE (collection_id, complex_id),
    CONSTRAINT uq_brc_target_collection_ordinal UNIQUE (collection_id, target_ordinal),
    CONSTRAINT ck_brc_target_ordinal CHECK (target_ordinal > 0),
    CONSTRAINT ck_brc_target_pnu CHECK (pnu ~ '^[0-9]{19}$'),
    CONSTRAINT ck_brc_target_initial_key CHECK (
        initial_bld_mgm_bld_rgst_pk IS NULL OR btrim(initial_bld_mgm_bld_rgst_pk) <> ''
    )
);

CREATE TABLE public.building_register_endpoint_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id uuid NOT NULL REFERENCES public.building_register_collection_campaign(collection_id),
    pnu character varying(19) NOT NULL,
    endpoint character varying(24) NOT NULL,
    run_date date NOT NULL,
    page_size integer NOT NULL,
    attempt_no integer NOT NULL,
    status character varying(32) NOT NULL,
    total_count integer,
    started_at timestamp with time zone DEFAULT now() NOT NULL,
    completed_at timestamp with time zone,
    CONSTRAINT uq_bre_snapshot_attempt UNIQUE (collection_id, pnu, endpoint, run_date, attempt_no),
    CONSTRAINT ck_bre_snapshot_pnu CHECK (pnu ~ '^[0-9]{19}$'),
    CONSTRAINT ck_bre_snapshot_endpoint CHECK (endpoint IN ('RECAP_TITLE', 'TITLE', 'BASIC_OVERVIEW')),
    CONSTRAINT ck_bre_snapshot_page_size CHECK (page_size IN (10, 25, 50, 100)),
    CONSTRAINT ck_bre_snapshot_attempt CHECK (attempt_no > 0),
    CONSTRAINT ck_bre_snapshot_total CHECK (total_count IS NULL OR total_count >= 0),
    CONSTRAINT ck_bre_snapshot_status CHECK (status IN (
        'ACTIVE', 'PARSED', 'EMPTY', 'ABANDONED_OVERSIZED', 'PERMANENT_OVERSIZED',
        'PROVIDER_FAILED', 'PARSE_FAILED'
    ))
);

CREATE TABLE public.building_register_raw_page (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_snapshot_id bigint NOT NULL REFERENCES public.building_register_endpoint_snapshot(id),
    request_id uuid NOT NULL,
    page_no integer NOT NULL,
    attempt_no integer NOT NULL,
    status character varying(24) NOT NULL,
    response_body text,
    body_sha256 character varying(64) NOT NULL,
    byte_count integer NOT NULL,
    http_status integer,
    provider_status character varying(32),
    failure_reason text,
    received_at timestamp with time zone DEFAULT now() NOT NULL,
    finalized_at timestamp with time zone,
    CONSTRAINT uq_brr_page_attempt UNIQUE (endpoint_snapshot_id, page_no, attempt_no),
    CONSTRAINT ck_brr_page_number CHECK (page_no > 0 AND attempt_no > 0),
    CONSTRAINT ck_brr_page_status CHECK (status IN (
        'RECEIVED', 'PARSED', 'EMPTY', 'PROVIDER_FAILED', 'PARSE_FAILED', 'OVERSIZED'
    )),
    CONSTRAINT ck_brr_page_hash CHECK (body_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_brr_page_bytes CHECK (byte_count >= 0),
    CONSTRAINT ck_brr_page_body_limit CHECK (
        response_body IS NULL OR octet_length(response_body) <= 2097152
    ),
    CONSTRAINT ck_brr_page_http_status CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599)
);

CREATE UNIQUE INDEX uq_brr_completed_page
    ON public.building_register_raw_page (endpoint_snapshot_id, page_no)
    WHERE status IN ('PARSED', 'EMPTY');

