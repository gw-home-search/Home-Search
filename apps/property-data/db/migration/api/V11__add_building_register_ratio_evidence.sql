CREATE TABLE public.building_register_complex_match (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id uuid NOT NULL REFERENCES public.building_register_collection_campaign(collection_id),
    complex_id bigint NOT NULL REFERENCES public.complex(id),
    pnu character varying(19) NOT NULL,
    root_management_key character varying(255),
    scope character varying(24) NOT NULL,
    status character varying(32) NOT NULL,
    match_path character varying(32),
    projectable boolean DEFAULT false NOT NULL,
    failure_reason text,
    evaluated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT uq_brcm_collection_complex UNIQUE (collection_id, complex_id),
    CONSTRAINT ck_brcm_pnu CHECK (pnu ~ '^[0-9]{19}$'),
    CONSTRAINT ck_brcm_root_key CHECK (root_management_key IS NULL OR btrim(root_management_key) <> ''),
    CONSTRAINT ck_brcm_scope CHECK (scope IN ('UNIQUE_ROOT', 'STANDALONE_TITLE', 'SHARED_RECAP')),
    CONSTRAINT ck_brcm_status CHECK (status IN (
        'RESOLVED', 'AMBIGUOUS', 'INCOMPLETE_HIERARCHY', 'SOURCE_CONFLICT',
        'AMBIGUOUS_GENERATION', 'SOURCE_MISSING'
    )),
    CONSTRAINT ck_brcm_match_path CHECK (match_path IS NULL OR match_path IN (
        'EXISTING_KEY', 'UNIQUE_PNU', 'EXACT_NAME', 'EXACT_DONG_SET', 'FOOTPRINT_EVIDENCE'
    )),
    CONSTRAINT ck_brcm_projectable CHECK (
        NOT projectable OR (status = 'RESOLVED' AND scope <> 'SHARED_RECAP')
    )
);

CREATE TABLE public.building_register_match_evidence (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES public.building_register_complex_match(id),
    evidence_type character varying(32) NOT NULL,
    outcome character varying(16) NOT NULL,
    evidence_value jsonb NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_brme_type CHECK (evidence_type IN (
        'EXISTING_KEY', 'PNU_CARDINALITY', 'EXACT_NAME', 'DONG_SET', 'FOOTPRINT_LINK',
        'DONG_COUNT', 'UNIT_COUNT', 'USE_DATE', 'HIERARCHY'
    )),
    CONSTRAINT ck_brme_outcome CHECK (outcome IN ('MATCH', 'MISMATCH', 'INCONCLUSIVE'))
);

CREATE TABLE public.building_ratio_candidate (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES public.building_register_complex_match(id),
    field character varying(32) NOT NULL,
    method character varying(48) NOT NULL,
    value numeric(18,8) NOT NULL,
    projected_value numeric(6,2) NOT NULL,
    numerator numeric(20,6),
    denominator numeric(20,6),
    status character varying(24) NOT NULL,
    selected boolean DEFAULT false NOT NULL,
    reason text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_brc_field CHECK (field IN ('BUILDING_COVERAGE_RATIO', 'FLOOR_AREA_RATIO')),
    CONSTRAINT ck_brc_method CHECK (method IN (
        'RECAP_DIRECT', 'RECAP_COMPONENT_CALC', 'TITLE_DIRECT_CONSENSUS',
        'RECAP_NUMERATOR_TITLE_DENOMINATOR', 'TITLE_AGGREGATE_CALC',
        'STANDALONE_TITLE_DIRECT', 'STANDALONE_TITLE_COMPONENT_CALC'
    )),
    CONSTRAINT ck_brc_value CHECK (value > 0 AND projected_value > 0 AND projected_value <= 9999.99),
    CONSTRAINT ck_brc_components CHECK (
        (numerator IS NULL OR numerator >= 0) AND (denominator IS NULL OR denominator > 0)
    ),
    CONSTRAINT ck_brc_status CHECK (status IN ('VALID', 'INCOMPLETE', 'SOURCE_CONFLICT')),
    CONSTRAINT uq_brc_identity_scope UNIQUE (id, match_id, field)
);

CREATE UNIQUE INDEX uq_brc_selected_field
    ON public.building_ratio_candidate (match_id, field)
    WHERE selected;

CREATE TABLE public.building_ratio_candidate_input (
    candidate_id bigint NOT NULL REFERENCES public.building_ratio_candidate(id),
    record_snapshot_id bigint NOT NULL REFERENCES public.building_register_record_snapshot(id),
    input_role character varying(24) NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    PRIMARY KEY (candidate_id, record_snapshot_id, input_role),
    CONSTRAINT ck_brci_role CHECK (input_role IN ('DIRECT', 'NUMERATOR', 'DENOMINATOR', 'HIERARCHY'))
);

CREATE TABLE public.building_ratio_projection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL,
    match_id bigint NOT NULL REFERENCES public.building_register_complex_match(id),
    candidate_id bigint,
    complex_id bigint NOT NULL REFERENCES public.complex(id),
    field character varying(32) NOT NULL,
    outcome character varying(40) NOT NULL,
    previous_value numeric(6,2),
    source_value numeric(6,2),
    applied_value numeric(6,2),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT uq_brp_request_candidate_field UNIQUE (request_id, candidate_id, field),
    CONSTRAINT uq_brp_request_match_field UNIQUE (request_id, match_id, field),
    CONSTRAINT fk_brp_candidate_scope FOREIGN KEY (candidate_id, match_id, field)
        REFERENCES public.building_ratio_candidate(id, match_id, field),
    CONSTRAINT ck_brp_field CHECK (field IN ('BUILDING_COVERAGE_RATIO', 'FLOOR_AREA_RATIO')),
    CONSTRAINT ck_brp_outcome CHECK (outcome IN (
        'APPLIED', 'ALREADY_EQUAL', 'SKIPPED_EXISTING_CONFLICT', 'SKIPPED_SHARED_SCOPE',
        'SKIPPED_SOURCE_CONFLICT', 'SOURCE_MISSING'
    )),
    CONSTRAINT ck_brp_candidate_outcome CHECK (
        (candidate_id IS NULL AND outcome = 'SOURCE_MISSING')
        OR (candidate_id IS NOT NULL AND outcome <> 'SOURCE_MISSING')
    )
);

